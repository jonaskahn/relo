  var codes = Object.keys(NAMES);

  function current() {
    var code = (root.lang || "en").split("-")[0];
    return DICT[code] ? code : "en";
  }

  function t(key) {
    var dict = DICT[current()];
    return dict[key] !== undefined ? dict[key] : DICT.en[key];
  }

  function markup(value) {
    return value.replace(/<a (\w+)>/g, function (_, id) {
      return '<a href="' + LINKS[id] + '">';
    });
  }

  function apply() {
    document.title = t("title");

    document.querySelectorAll("[data-i18n]").forEach(function (node) {
      node.innerHTML = markup(t(node.dataset.i18n));
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(function (node) {
      node.dataset.i18nAttr.split(";").forEach(function (pair) {
        var parts = pair.split(":");
        node.setAttribute(parts[0], t(parts[1]));
      });
    });
  }

  function setLang(code) {
    root.lang = code === "zh" ? "zh-Hans" : code;
    root.dir = code === "ar" || code === "ur" ? "rtl" : "ltr";
    apply();
    document.dispatchEvent(new CustomEvent("relo:lang"));
  }

  var select = document.getElementById("lang");

  if (select) {
    codes.forEach(function (code) {
      var option = document.createElement("option");
      option.value = code;
      option.textContent = NAMES[code];
      option.lang = code === "zh" ? "zh-Hans" : code;
      select.appendChild(option);
    });
    select.value = current();
    select.addEventListener("change", function () {
      try { localStorage.setItem("relo-lang", select.value); } catch (e) {}
      setLang(select.value);
    });
  }

  window.relo = { t: t };
  setLang(current());
